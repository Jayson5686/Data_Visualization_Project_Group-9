const languageOptions = {
  en: { lang: "en-AU", index: -1 },
  "zh-CN": { lang: "zh-CN", index: 0 },
  ms: { lang: "ms", index: 1 },
  ja: { lang: "ja", index: 2 }
};

const normalized = value => value.trim().replace(/\s+/g, " ");
const elementSources = new WeakMap();
const attributeSources = new WeakMap();
const textSources = new WeakMap();
const sourceDocumentTitle = document.title;

function translatePhrase(value, language) {
  if (language === "en") return value;
  const index = languageOptions[language].index;
  const direct = languageCatalog[value];
  if (direct) return direct[index];
  const normalizedValue = normalized(value);
  const normalizedDirect = languageCatalog[normalizedValue];
  if (normalizedDirect) return normalizedDirect[index];

  const prefix = Object.keys(languageCatalog).find(key => value.startsWith(key));
  if (prefix) {
    return languageCatalog[prefix][index] + value.slice(prefix.length).replace(/^\s+/, "");
  }
  const dayCount = value.match(/^([\d,.]+)\s+days(.*)$/);
  if (dayCount) {
    const suffix = dayCount[2].trim();
    return `${dayCount[1]} ${translatePhrase("days", language)}${suffix ? ` ${translatePhrase(suffix, language)}` : ""}`;
  }
  const trajectory = value.match(/^(.+?) Trajectory$/);
  if (trajectory) return `${trajectory[1]} ${translatePhrase("Trajectory", language)}`;
  return value;
}

function translateTextNode(node, language) {
  let state = textSources.get(node);
  const current = node.nodeValue;
  if (!state || (current !== state.rendered && current !== state.source)) {
    state = { source: current, rendered: current };
    textSources.set(node, state);
  }
  const leading = state.source.match(/^\s*/)[0];
  const trailing = state.source.match(/\s*$/)[0];
  const translated = translatePhrase(state.source.trim(), language);
  state.rendered = `${leading}${translated}${trailing}`;
  if (current !== state.rendered) node.nodeValue = state.rendered;
}

function translateElementText(element, language) {
  if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(element.tagName)) return false;
  if ([...element.children].length) return false;

  let state = elementSources.get(element);
  const currentText = normalized(element.textContent);

  if (state) {
    if (currentText !== state.rendered && currentText !== state.text) {
      state = { text: currentText, html: element.innerHTML, rendered: currentText };
      elementSources.set(element, state);
    }
  } else if (languageCatalog[currentText]) {
    state = { text: currentText, html: element.innerHTML, rendered: currentText };
    elementSources.set(element, state);
  } else {
    return false;
  }

  const translated = translatePhrase(state.text, language);
  state.rendered = translated;
  if (language === "en") {
    if (element.innerHTML !== state.html) element.innerHTML = state.html;
  } else if (element.textContent !== translated) {
    element.textContent = translated;
  }
  return true;
}

function translateAttributes(element, language) {
  ["aria-label", "aria-description", "title", "alt", "placeholder", "content"].forEach(attribute => {
    if (!element.hasAttribute(attribute)) return;
    let sources = attributeSources.get(element);
    if (!sources) {
      sources = new Map();
      attributeSources.set(element, sources);
    }
    let state = sources.get(attribute);
    const current = element.getAttribute(attribute);
    if (!state || (current !== state.rendered && current !== state.source)) {
      state = { source: current, rendered: current };
      sources.set(attribute, state);
    }
    state.rendered = translatePhrase(state.source, language);
    if (current !== state.rendered) element.setAttribute(attribute, state.rendered);
  });
}

function translateSubtree(node, language) {
  if (node.nodeType === Node.TEXT_NODE) {
    translateTextNode(node, language);
    return;
  }
  if (!(node instanceof Element)) return;
  if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.tagName)) return;

  translateAttributes(node, language);
  if (translateElementText(node, language)) return;
  node.childNodes.forEach(child => translateSubtree(child, language));
}

function initializeLanguageSelector() {
  const selector = document.getElementById("language-selector");
  if (!selector) return;

  let language = "en";
  try {
    const savedLanguage = localStorage.getItem("crashmetrics-language");
    if (savedLanguage && Object.hasOwn(languageOptions, savedLanguage)) language = savedLanguage;
  } catch (error) {
    console.warn("Unable to read saved language preference:", error);
  }

  const applyLanguage = value => {
    language = value;
    selector.value = language;
    document.documentElement.lang = languageOptions[language].lang;
    document.documentElement.dataset.language = language;
    document.title = translatePhrase(sourceDocumentTitle, language);
    translateSubtree(document.documentElement, language);
  };

  applyLanguage(language);
  selector.addEventListener("change", () => {
    applyLanguage(selector.value);
    try {
      localStorage.setItem("crashmetrics-language", language);
    } catch (error) {
      console.warn("Unable to save language preference:", error);
    }
  });

  new MutationObserver(records => {
    records.forEach(record => {
      if (record.type === "attributes") {
        translateAttributes(record.target, language);
        return;
      }
      if (record.type === "characterData") {
        translateSubtree(record.target, language);
        return;
      }
      record.addedNodes.forEach(node => translateSubtree(node, language));
    });
  }).observe(document.body, {
    attributes: true,
    attributeFilter: ["aria-label", "aria-description", "title", "alt", "placeholder", "content"],
    childList: true,
    characterData: true,
    subtree: true
  });
}

window.translateCrashMetrics = translatePhrase;
initializeLanguageSelector();
